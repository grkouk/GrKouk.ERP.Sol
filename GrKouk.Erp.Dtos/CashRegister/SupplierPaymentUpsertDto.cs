using System;

namespace GrKouk.Erp.Dtos.CashRegister;

public class SupplierPaymentUpsertDto
{
    public int? Id { get; set; }
    public string CompanyCode { get; set; }
    public int TransactorId { get; set; }
    public int CfAccountId { get; set; }
    public DateTime TransDate { get; set; }
    public string TransRefCode { get; set; }
    public decimal AmountNet { get; set; }
    public decimal AmountFpa { get; set; }
    public decimal AmountDiscount { get; set; }
    public decimal FpaRate { get; set; }
    public decimal DiscountRate { get; set; }
    public string Etiology { get; set; }
    public byte[] Timestamp { get; set; }

    // Filled only when the payment is read back; ignored on create and update.

    /// <summary>True when a document (a buy document paid on the spot) created this payment.
    /// Such a payment belongs to its document and cannot be changed or deleted on its own.</summary>
    public bool IsAutoGenerated { get; set; }

    /// <summary>The buy document that created the payment, when it could be found.</summary>
    public string SourceDocSeriesName { get; set; }
    public string SourceDocRefCode { get; set; }
    public DateTime? SourceDocDate { get; set; }
    public string SourcePaymentMethodName { get; set; }
}
